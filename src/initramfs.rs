/// Writer for the SVR4 `newc` cpio format.
#[derive(Default)]
pub struct CpioWriter {
    out: Vec<u8>,
    next_ino: u32,
}

impl CpioWriter {
    pub fn new() -> Self {
        CpioWriter { out: Vec::new(), next_ino: 1 }
    }

    fn pad4(out: &mut Vec<u8>) {
        while !out.len().is_multiple_of(4) {
            out.push(0);
        }
    }

    /// Append one archive member.
    pub fn add(&mut self, m: &Member) {
        let ino = self.next_ino;
        self.next_ino += 1;
        let header = format!(
            "070701{:08x}{:08x}{:08x}{:08x}{:08x}{:08x}{:08x}{:08x}{:08x}{:08x}{:08x}{:08x}{:08x}",
            ino,
            m.mode,
            m.uid,
            m.gid,
            1, // nlink
            m.mtime,
            m.data.len() as u32,
            0,
            0,
            m.rdev.0,
            m.rdev.1,
            m.name.len() as u32 + 1,
            0,
        );
        self.out.extend_from_slice(header.as_bytes());
        self.out.extend_from_slice(m.name.as_bytes());
        self.out.push(0);
        Self::pad4(&mut self.out);
        self.out.extend_from_slice(&m.data);
        Self::pad4(&mut self.out);
    }

    /// Terminate the archive and return it.
    pub fn finish(mut self) -> Vec<u8> {
        self.add(&Member::new("TRAILER!!!", 0, Vec::new()));
        self.out
    }
}

/// One archive member, ready to be written.
#[derive(Clone, Debug)]
pub struct Member {
    pub name: String,
    pub mode: u32,
    pub uid: u32,
    pub gid: u32,
    pub mtime: u32,
    pub rdev: (u32, u32),
    pub data: Vec<u8>,
}

impl Member {
    fn new(name: &str, mode: u32, data: Vec<u8>) -> Self {
        Member { name: name.to_string(), mode, uid: 0, gid: 0, mtime: 0, rdev: (0, 0), data }
    }
}

fn normalize(path: &Path) -> String {
    let s = path.to_string_lossy();
    s.trim_start_matches("./").trim_start_matches('/').trim_end_matches('/').to_string()
}

/// Members of the root tarball.
fn tarball_members(tar_gz: &[u8]) -> io::Result<Vec<Member>> {
    let mut archive = tar::Archive::new(flate2::read::GzDecoder::new(tar_gz));
    let mut out: Vec<Member> = Vec::new();
    // Hard links are materialized as copies. Index the existing members so
    // packing does not duplicate the data of files without hard links.
    let mut contents: HashMap<String, usize> = HashMap::new();

    for entry in archive.entries()? {
        let mut entry = entry?;
        let name = normalize(&entry.path()?);
        if name.is_empty() {
            continue;
        }
        let header = entry.header();
        let mode = header.mode()? & 0o7777;
        let uid = header.uid()? as u32;
        let gid = header.gid()? as u32;
        let mtime = header.mtime()? as u32;
        let kind = header.entry_type();
        // Device numbers are only meaningful for device entries.
        let (major, minor) = match kind {
            EntryType::Char | EntryType::Block => (
                header.device_major().ok().flatten().unwrap_or(0),
                header.device_minor().ok().flatten().unwrap_or(0),
            ),
            _ => (0, 0),
        };
        let member = match kind {
            EntryType::Regular | EntryType::Continuous | EntryType::GNUSparse => {
                let mut data = Vec::new();
                entry.read_to_end(&mut data)?;
                contents.insert(name.clone(), out.len());
                Member { name, mode: 0o100000 | mode, uid, gid, mtime, rdev: (0, 0), data }
            }
            EntryType::Directory => Member { name, mode: 0o040000 | mode, uid, gid, mtime, rdev: (0, 0), data: Vec::new() },
            EntryType::Symlink => {
                let target = entry.link_name()?.map(|p| p.to_string_lossy().into_owned()).unwrap_or_default();
                Member { name, mode: 0o120777, uid, gid, mtime, rdev: (0, 0), data: target.into_bytes() }
            }
            EntryType::Link => {
                let target = entry.link_name()?.map(|p| normalize(&p)).unwrap_or_default();
                let data = contents.get(&target).map(|&index| out[index].data.clone()).unwrap_or_default();
                contents.insert(name.clone(), out.len());
                Member { name, mode: 0o100000 | mode, uid, gid, mtime, rdev: (0, 0), data }
            }
            EntryType::Char => Member { name, mode: 0o020000 | mode, uid, gid, mtime, rdev: (major, minor), data: Vec::new() },
            EntryType::Block => Member { name, mode: 0o060000 | mode, uid, gid, mtime, rdev: (major, minor), data: Vec::new() },
            EntryType::Fifo => Member { name, mode: 0o010000 | mode, uid, gid, mtime, rdev: (0, 0), data: Vec::new() },
            _ => continue,
        };
        out.push(member);
    }
    Ok(out)
}

/// Members of an overlay directory, named relative to its root. Files keep
/// their permissions, and symbolic links are preserved.
pub fn overlay_members(root: &Path) -> io::Result<Vec<Member>> {
    let mut out = Vec::new();
    let mut stack = vec![PathBuf::new()];
    while let Some(rel) = stack.pop() {
        let dir = root.join(&rel);
        let mut entries: Vec<_> = fs::read_dir(&dir)?.collect::<Result<_, _>>()?;
        entries.sort_by_key(|e| e.file_name());
        for entry in entries {
            let rel_path = rel.join(entry.file_name());
            let path = entry.path();
            let meta = fs::symlink_metadata(&path)?;
            let name = normalize(&rel_path);
            let mode_bits = meta.permissions().mode() & 0o7777;
            let mtime = meta.mtime() as u32;
            let ft = meta.file_type();
            let member = if ft.is_symlink() {
                let target = fs::read_link(&path)?;
                Member { name, mode: 0o120777, uid: 0, gid: 0, mtime, rdev: (0, 0), data: target.to_string_lossy().into_owned().into_bytes() }
            } else if ft.is_dir() {
                stack.push(rel_path);
                Member { name, mode: 0o040000 | mode_bits, uid: 0, gid: 0, mtime, rdev: (0, 0), data: Vec::new() }
            } else {
                Member { name, mode: 0o100000 | mode_bits, uid: 0, gid: 0, mtime, rdev: (0, 0), data: fs::read(&path)? }
            };
            out.push(member);
        }
    }
    Ok(out)
}

/// Options for building the initial root filesystem.
#[derive(Clone, Debug, Default)]
pub struct RootfsOptions {
    /// Program to run as PID 1 instead of the generated `/init`.
    pub init: Option<String>,
    /// Settings for the generated `/init`.
    pub init_options: InitOptions,
    /// Directories whose contents are added on top of the rootfs.
    pub overlays: Vec<PathBuf>,
}

/// Build the root filesystem from a gzip-compressed tarball and return it as cpio.
///
/// Overlay files replace rootfs entries with the same path. An overlay that
/// provides `/init` also suppresses the generated one.
pub fn build_rootfs(tar_gz: &[u8], opts: &RootfsOptions) -> io::Result<Vec<u8>> {
    let mut members = tarball_members(tar_gz)?;
    if opts.init_options.omit_rootfs {
        // Keep only what the init script needs to mount the root disk: the
        // shell (BusyBox) and the C library it links against.
        members.retain(|m| matches!(m.name.as_str(),
            "bin" | "lib" |
            "bin/busybox" |
            "lib/libc.musl-riscv64.so.1" |
            "lib/ld-musl-riscv64.so.1"));
    }
    for dir in &opts.overlays {
        members.extend(overlay_members(dir)?);
    }
    // The kernel does not create the directories of a file it unpacks, and a root
    // file system left out of the initramfs has none of them.
    {
        let have: std::collections::HashSet<String> = members.iter().map(|m| m.name.clone()).collect();
        let mut dir = String::new();
        let parent = RSSH_PATH.rsplit_once('/').map_or("", |(d, _)| d);
        for part in parent.split('/').filter(|p| !p.is_empty()) {
            if !dir.is_empty() {
                dir.push('/');
            }
            dir.push_str(part);
            if !have.contains(&dir) {
                members.push(Member::new(&dir, 0o040755, Vec::new()));
            }
        }
    }
    members.push(Member::new(RSSH_PATH, 0o100755, RSSH.as_bytes().to_vec()));
    let overlay_has_init = opts.overlays.iter().any(|d| d.join("init").exists());

    // A later member with the same name replaces the earlier contents, as an
    // overlay does on a real disk. It keeps the earlier position, so a parent
    // directory is still unpacked before the files inside it.
    let mut position: HashMap<String, usize> = HashMap::new();
    let mut unique: Vec<Member> = Vec::new();
    for m in members {
        match position.get(&m.name) {
            Some(&i) => unique[i] = m,
            None => {
                position.insert(m.name.clone(), unique.len());
                unique.push(m);
            }
        }
    }

    if !overlay_has_init && !position.contains_key("init") {
        let script = match &opts.init {
            Some(program) => {
                let target = if program.starts_with('/') { program.clone() } else { format!("/{program}") };
                unique.push(Member::new("init", 0o120777, target.into_bytes()));
                None
            }
            None if opts.init_options.omit_rootfs => Some(mount_only_init(&opts.init_options)),
            None => Some(default_init(&opts.init_options)),
        };
        if let Some(script) = script {
            unique.push(Member::new("init", 0o100755, script.into_bytes()));
        }
    }

    let mut cpio = CpioWriter::new();
    for m in &unique {
        cpio.add(m);
    }
    Ok(cpio.finish())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cpio_header_is_newc() {
        let mut w = CpioWriter::new();
        w.add(&Member::new("a", 0o100644, b"hi".to_vec()));
        let out = w.finish();
        assert_eq!(&out[0..6], b"070701");
        assert_eq!(out.len() % 4, 0);
        assert!(out.windows(10).any(|w| w == b"TRAILER!!!"));
    }

    #[test]
    fn debug_minimal_names() {
        let Ok(tgz) = std::fs::read("examples/work/alpine-minirootfs-3.24.2-riscv64.tar.gz") else {
            return;
        };
        let mut members = tarball_members(&tgz).unwrap();
        members.retain(|m| matches!(m.name.as_str(),
            "bin" | "lib" |
            "bin/busybox" |
            "lib/libc.musl-riscv64.so.1" |
            "lib/ld-musl-riscv64.so.1"));
        eprintln!("kept: {:?}", members.iter().map(|m| m.name.clone()).collect::<Vec<_>>());
        let opts = RootfsOptions {
            init: None,
            init_options: InitOptions { omit_rootfs: true, ..Default::default() },
            overlays: Vec::new(),
        };
        let cpio = build_rootfs(&tgz, &opts).unwrap();
        std::fs::write("/tmp/rvbench/minimal.cpio", &cpio).unwrap();
        eprintln!("cpio bytes: {}", cpio.len());
    }

    #[test]
    fn init_loads_modules_and_network_on_request() {
        let plain = default_init(&InitOptions::default());
        assert!(!plain.contains("insmod"));
        let full = default_init(&InitOptions { modules: VIRTIO_CORE.to_vec(), network: true, ..Default::default() });
        assert!(full.contains("insmod"));
        assert!(full.contains("ip addr add 10.0.2.15/24"));
        assert!(!full.contains("fd00:2::15"));
        let v6 = default_init(&InitOptions { network: true, network_ipv6: true, ..Default::default() });
        assert!(v6.contains("ip -6 addr add fd00:2::15/64 dev eth0"));
        assert!(v6.contains("ip -6 route add default via fd00:2::2 dev eth0"));
    }

    #[test]
    fn init_scripts_are_valid_shell() {
        let variants = [
            InitOptions::default(),
            InitOptions { modules: VIRTIO_CORE.to_vec(), network: true, network_ipv6: true, ..Default::default() },
            InitOptions { modules: VIRTIO_BLK.to_vec(), network: true, persistent_root: true, ..Default::default() },
        ];
        let dir = std::env::temp_dir();
        for (i, opts) in variants.iter().enumerate() {
            let path = dir.join(format!("rvemu-init-test-{}-{i}.sh", std::process::id()));
            std::fs::write(&path, default_init(opts)).unwrap();
            // `sh -n` only parses, so the script is not run.
            if let Ok(out) = std::process::Command::new("sh").arg("-n").arg(&path).output() {
                assert!(out.status.success(), "variant {i}: {}", String::from_utf8_lossy(&out.stderr));
            }
            std::fs::remove_file(&path).unwrap();
        }
    }

    #[test]
    fn persistent_root_is_only_in_its_variant() {
        let plain = default_init(&InitOptions { network: true, ..Default::default() });
        assert!(!plain.contains("switch_root"));
        let root = default_init(&InitOptions { persistent_root: true, ..Default::default() });
        assert!(root.contains("exec switch_root /newroot /sbin/rvemu-session"));
        // The memory-root shell follows the persistent-root block as the fallback.
        assert!(root.matches("setsid -c /bin/sh -l").count() == 2);
    }

    /// The helper is in the memory root, also when the rootfs is left out, and the
    /// persistent root refreshes its copy from there at every boot.
    #[test]
    fn rssh_is_installed_and_refreshed() {
        for omit in [false, true] {
            let tgz = {
                let mut gz = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::fast());
                tar::Builder::new(&mut gz).finish().unwrap();
                gz.finish().unwrap()
            };
            let opts = RootfsOptions {
                init: None,
                init_options: InitOptions { omit_rootfs: omit, persistent_root: true, ..Default::default() },
                overlays: Vec::new(),
            };
            let cpio = build_rootfs(&tgz, &opts).unwrap();
            let has = |needle: &[u8]| cpio.windows(needle.len()).any(|w| w == needle);
            // Member names in archive order: the kernel only unpacks a file whose
            // directory is already there (this was missing on the phone).
            let mut names = Vec::new();
            let mut at = 0;
            while at + 110 <= cpio.len() {
                let field = |i: usize| usize::from_str_radix(std::str::from_utf8(&cpio[at + 6 + 8 * i..at + 14 + 8 * i]).unwrap(), 16).unwrap();
                let (size, namesize) = (field(6), field(11));
                let name = String::from_utf8_lossy(&cpio[at + 110..at + 110 + namesize - 1]).into_owned();
                if name == "TRAILER!!!" {
                    break;
                }
                names.push(name);
                at = (at + 110 + namesize + 3) & !3;
                at = (at + size + 3) & !3;
            }
            let index = |n: &str| names.iter().position(|x| x == n);
            let file = index("usr/local/bin/rssh").unwrap_or_else(|| panic!("no rssh, omit_rootfs={omit}: {names:?}"));
            for dir in ["usr", "usr/local", "usr/local/bin"] {
                let d = index(dir).unwrap_or_else(|| panic!("no {dir}, omit_rootfs={omit}: {names:?}"));
                assert!(d < file, "{dir} must come before the file, omit_rootfs={omit}");
            }
            assert!(has(b"usr/local/bin/rssh"), "omit_rootfs={omit}");
            assert!(has(b"# rssh - find your devices"), "omit_rootfs={omit}");
            assert!(has(b"cp /usr/local/bin/rssh /newroot/usr/local/bin/rssh && : > "), "omit_rootfs={omit}");
            assert!(has(format!("[ -e /newroot/usr/local/bin/.rssh-{} ]", rssh_tag()).as_bytes()), "omit_rootfs={omit}");
        }
    }
}
