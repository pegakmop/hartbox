/// Kernel modules for the virtio devices, in dependency order. Each is loaded
/// from `/lib/rvemu` when the overlay provides it.
pub const VIRTIO_CORE: &[&str] = &["virtio_ring", "virtio", "virtio_mmio"];
pub const VIRTIO_RNG: &[&str] = &["virtio-rng"];
pub const VIRTIO_BLK: &[&str] = &["virtio_blk"];
pub const VIRTIO_NET: &[&str] = &["failover", "net_failover", "virtio_net"];
/// Modules for an ext4 root filesystem (ext4 needs jbd2 and mbcache).
pub const EXT4: &[&str] = &["crc16", "mbcache", "jbd2", "ext4"];

/// `rssh`, the ssh helper (tools/rssh), installed as /usr/local/bin/rssh. It is
/// one POSIX shell script that runs in the guest and on the host.
pub const RSSH: &str = include_str!("../tools/rssh");

/// Where the guest gets `rssh`, and where the persistent root's copy is refreshed from.
const RSSH_PATH: &str = "usr/local/bin/rssh";

/// A name for this version of `rssh` (FNV-1a over its text). The persistent root
/// keeps a marker file with it; when the marker exists the copy is current, and
/// the boot checks that with the shell's own `[ -e ]`: a command such as `cmp`
/// would be a process of its own, about a million instructions on every boot.
fn rssh_tag() -> String {
    let mut h = 0xcbf2_9ce4_8422_2325u64;
    for &b in RSSH.as_bytes() {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

/// What the generated `/init` should set up.
#[derive(Clone, Debug, Default)]
pub struct InitOptions {
    /// Kernel modules to insmod from `/lib/rvemu`, in order. Missing files are skipped.
    pub modules: Vec<&'static str>,
    /// Modules loaded by the login session, in the background, after the
    /// shell is already interactive. Only the `mount_only_init` path uses it,
    /// to keep the network stack off the boot's critical path.
    pub late_modules: Vec<&'static str>,
    /// Mount the first virtio disk as the root filesystem and continue from it.
    /// The disk is populated from the memory root on first use.
    pub persistent_root: bool,
    /// Configure `eth0` with the gateway addressing used by `--net`.
    pub network: bool,
    /// Also configure IPv6 on `eth0` (fd00:2::/64, see `net`).
    pub network_ipv6: bool,
    /// Console size to set before the shell starts (`stty cols rows`), for
    /// embedders whose display is narrower than 80 columns.
    pub console_size: Option<(u16, u16)>,
    /// Leave the root filesystem out of the initramfs and boot straight from
    /// the persistent root disk. Only valid when that disk is already
    /// populated; the guest then skips the kernel's unpack of a whole rootfs.
    pub omit_rootfs: bool,
}

/// The `/init` script. It mounts the virtual filesystems, prepares devices and
/// networking, and runs a shell on the console. When the shell exits the
/// machine powers off.
pub fn default_init(opts: &InitOptions) -> String {
    let mut s = String::from(
        "#!/bin/sh\n\
         # /init generated by rvemu\n\
         mount -t proc proc /proc\n\
         mount -t sysfs sysfs /sys\n\
         mount -t devtmpfs devtmpfs /dev\n\
         mkdir -p /dev/pts /dev/shm /run /tmp\n\
         mount -t devpts devpts /dev/pts\n\
         mount -t tmpfs tmpfs /run\n\
         mount -t tmpfs tmpfs /tmp\n",
    );
    if !opts.modules.is_empty() {
        // One `modprobe -a` inserts every module in a single process, instead
        // of forking BusyBox per module. Any failure falls back to insmod.
        s.push_str("if command -v modprobe >/dev/null 2>&1; then\n");
        s.push_str("\tk=$(uname -r)\n\tmkdir -p /lib/modules/$k\n");
        s.push_str("\tcat > /lib/modules/$k/modules.dep <<'RVEMU_MODULES'\n");
        for m in &opts.modules {
            s.push_str("/lib/rvemu/");
            s.push_str(m);
            s.push_str(".ko:\n");
        }
        s.push_str("RVEMU_MODULES\n\tmodprobe -a");
        for m in &opts.modules {
            s.push(' ');
            s.push_str(m);
        }
        s.push_str(" >/dev/null 2>&1\nelse\n\tfor m in");
        for m in &opts.modules {
            s.push(' ');
            s.push_str(m);
        }
        s.push_str("; do\n\t\tf=/lib/rvemu/$m.ko\n\t\t[ -f \"$f\" ] && insmod \"$f\" >/dev/null 2>&1\n\tdone\nfi\n");
    }
    // The network stack is the slowest part of bring-up, and the shell must
    // not start before it: a resolver with no interface reports "temporary
    // failure" for the first commands a user types. Load the modules in the
    // background and join them before touching the link, so the load overlaps
    // the rest of the boot instead of following the prompt.
    if !opts.late_modules.is_empty() {
        s.push_str("(\n\tk=$(uname -r)\n\tmkdir -p /lib/modules/$k\n");
        s.push_str("\tcat >> /lib/modules/$k/modules.dep <<'RVEMU_LATE_DEPS'\n");
        for m in &opts.late_modules {
            s.push_str("/lib/rvemu/");
            s.push_str(m);
            s.push_str(".ko:\n");
        }
        s.push_str("RVEMU_LATE_DEPS\n\tmodprobe -a");
        for m in &opts.late_modules {
            s.push(' ');
            s.push_str(m);
        }
        s.push_str(" >/dev/null 2>&1\n) >/dev/null 2>&1 &\nwait\n");
    }
    if opts.network {
        s.push_str(
            "if [ -d /sys/class/net/eth0 ]; then\n\
             \tip link set eth0 up\n\
             \tip addr add 10.0.2.15/24 dev eth0\n\
             \tip route add default via 10.0.2.2\n\
             \techo 'nameserver 10.0.2.3' > /etc/resolv.conf\n",
        );
        if opts.network_ipv6 {
            // The gateway answers neighbor discovery, so duplicate address
            // detection is not needed: the address is used at once.
            s.push_str(
                "\techo 0 > /proc/sys/net/ipv6/conf/eth0/accept_dad 2>/dev/null\n\
                 \techo 0 > /proc/sys/net/ipv6/conf/eth0/dad_transmits 2>/dev/null\n\
                 \tip -6 addr add fd00:2::15/64 dev eth0\n\
                 \tip -6 route add default via fd00:2::2 dev eth0\n\
                 \techo 'nameserver fd00:2::3' >> /etc/resolv.conf\n",
            );
        }
        s.push_str("fi\n");
    }
    if let Some((cols, rows)) = opts.console_size {
        s.push_str(&format!("stty cols {cols} rows {rows} 2>/dev/null\n"));
    }
    if opts.persistent_root {
        s.push_str(&persistent_root());
    }
    // Reached when there is no persistent root, or it could not be mounted.
    s.push_str(SESSION);
    s
}

/// The `/init` used when the initramfs carries no root filesystem: load the
/// modules, mount the already-populated root disk and switch to it. Every
/// applet is called through BusyBox by absolute path, so no symlink farm is
/// needed and the initramfs stays a couple of megabytes.
pub fn mount_only_init(opts: &InitOptions) -> String {
    let mut s = String::from(
        "#!/bin/busybox sh\n\
         # /init generated by rvemu (root disk already populated)\n\
         BB=/bin/busybox\n\
         $BB mkdir -p /proc /sys /dev /newroot /lib/modules\n\
         $BB mount -t proc proc /proc\n\
         $BB mount -t sysfs sysfs /sys\n\
         $BB mount -t devtmpfs devtmpfs /dev\n",
    );
    if !opts.modules.is_empty() {
        s.push_str("k=$($BB uname -r)\n$BB mkdir -p /lib/modules/$k\n");
        s.push_str("$BB cat > /lib/modules/$k/modules.dep <<'RVEMU_MODULES'\n");
        for m in &opts.modules {
            s.push_str("/lib/rvemu/");
            s.push_str(m);
            s.push_str(".ko:\n");
        }
        s.push_str("RVEMU_MODULES\n$BB modprobe -a");
        for m in &opts.modules {
            s.push(' ');
            s.push_str(m);
        }
        s.push_str(" >/dev/null 2>&1\n");
    }
    // The network modules load while the root disk is mounted. The session
    // joins them through the `wait` before `switch_root`, then brings the link
    // up before the shell starts.
    if !opts.late_modules.is_empty() {
        s.push_str("(\n\tk=$($BB uname -r)\n\t$BB mkdir -p /lib/modules/$k\n");
        s.push_str("\t$BB cat >> /lib/modules/$k/modules.dep <<'RVEMU_LATE_DEPS'\n");
        for m in &opts.late_modules {
            s.push_str("/lib/rvemu/");
            s.push_str(m);
            s.push_str(".ko:\n");
        }
        s.push_str("RVEMU_LATE_DEPS\n\t$BB modprobe -a");
        for m in &opts.late_modules {
            s.push(' ');
            s.push_str(m);
        }
        s.push_str(" >/dev/null 2>&1\n) >/dev/null 2>&1 &\n");
    }
    s.push_str("if $BB mount -t ext4 -o noatime /dev/vda /newroot 2>/dev/null; then\n");
    s.push_str("\t$BB mkdir -p /newroot/sbin /newroot/proc /newroot/sys /newroot/dev /newroot/etc /newroot/usr/local/bin\n");
    // The root disk keeps its own files across boots, so the helper is refreshed
    // from the memory root; it is only written when it changed.
    let m = format!("/newroot/usr/local/bin/.rssh-{}", rssh_tag());
    s.push_str(&format!(
        "\t[ -e {m} ] || {{ $BB rm -f /newroot/usr/local/bin/.rssh-*; $BB cp /usr/local/bin/rssh /newroot/usr/local/bin/rssh && : > {m}; }} 2>/dev/null\n"
    ));
    s.push_str("\t$BB cat > /newroot/sbin/rvemu-session <<'RVEMU_SESSION'\n#!/bin/busybox sh\nBB=/bin/busybox\n");
    // `switch_root` does not always carry /proc and /sys over, and without them
    // the session cannot see the network device or configure it. Mount them
    // here if they are missing: `[ -f /proc/uptime ]` is a shell builtin, so a
    // boot where they are already there pays nothing.
    s.push_str("[ -f /proc/uptime ] || $BB mount -t proc proc /proc 2>/dev/null\n");
    s.push_str("[ -d /sys/class/net ] || $BB mount -t sysfs sysfs /sys 2>/dev/null\n");
    s.push_str("[ -c /dev/null ] || $BB mount -t devtmpfs devtmpfs /dev 2>/dev/null\n");
    s.push_str("$BB mkdir -p /dev/pts /dev/shm /run /tmp\n");
    s.push_str("$BB mount -t devpts devpts /dev/pts 2>/dev/null\n");
    s.push_str("$BB mount -t tmpfs tmpfs /run 2>/dev/null\n");
    s.push_str("$BB mount -t tmpfs tmpfs /tmp 2>/dev/null\n");
    // The link is configured here, before the shell, so the first command a
    // user types can resolve names. `/init` loads the modules in the
    // background; repeat that only if it did not finish.
    if !opts.late_modules.is_empty() {
        s.push_str("[ -d /sys/class/net/eth0 ] || {\n\tk=$($BB uname -r)\n");
        s.push_str("$BB mkdir -p /lib/modules/$k\n");
        s.push_str("$BB cat >> /lib/modules/$k/modules.dep <<'RVEMU_LATE_DEPS'\n");
        for m in &opts.late_modules {
            s.push_str("/lib/rvemu/");
            s.push_str(m);
            s.push_str(".ko:\n");
        }
        s.push_str("RVEMU_LATE_DEPS\n$BB modprobe -a");
        for m in &opts.late_modules {
            s.push(' ');
            s.push_str(m);
        }
        s.push_str(" >/dev/null 2>&1\n}\n");
    }
    if opts.network {
        // The link is configured unconditionally: the session has no reliable
        // way to ask whether the device exists (and `ip` reports it itself when
        // it does not), while a missed configuration leaves the guest without a
        // network for the whole session.
        s.push_str("$BB ip link set eth0 up 2>/dev/null\n");
        s.push_str("$BB ip addr add 10.0.2.15/24 dev eth0 2>/dev/null\n");
        s.push_str("$BB ip route add default via 10.0.2.2 2>/dev/null\n");
        s.push_str("$BB echo 'nameserver 10.0.2.3' > /etc/resolv.conf\n");
        if opts.network_ipv6 {
            s.push_str("$BB echo 0 > /proc/sys/net/ipv6/conf/eth0/accept_dad 2>/dev/null\n");
            s.push_str("$BB echo 0 > /proc/sys/net/ipv6/conf/eth0/dad_transmits 2>/dev/null\n");
            s.push_str("$BB ip -6 addr add fd00:2::15/64 dev eth0 2>/dev/null\n");
            s.push_str("$BB ip -6 route add default via fd00:2::2 dev eth0 2>/dev/null\n");
            s.push_str("$BB echo 'nameserver fd00:2::3' >> /etc/resolv.conf\n");
        }
    }
    s.push_str(SESSION);
    s.push_str("RVEMU_SESSION\n\t$BB chmod 755 /newroot/sbin/rvemu-session\n");
    s.push_str("\twait\n");
    s.push_str("\texec $BB switch_root /newroot /sbin/rvemu-session\n");
    s.push_str("fi\n");
    s.push_str("$BB echo 'rvemu: cannot mount the root disk' > /dev/console\n");
    s.push_str("exec $BB sh\n");
    s
}

/// Mount the first virtio disk as the root filesystem and `switch_root` into
/// it. The host formats the disk; the memory root is copied onto it on first
/// use. If the disk cannot be mounted, the session continues from memory.
fn persistent_root() -> String {
    String::from(
        "\
if [ -b /dev/vda ] && grep -qw ext4 /proc/filesystems && command -v switch_root >/dev/null 2>&1; then\n\
\tmkdir -p /newroot\n\
\tif mount -t ext4 -o noatime /dev/vda /newroot 2>/dev/null; then\n\
\t\tif [ ! -s /newroot/etc/rvemu-root ]; then\n\
\t\t\techo 'rvemu: preparing the root disk (first boot)'\n\
\t\t\tcopied=1\n\
\t\t\tfor d in /*; do\n\
\t\t\t\tcase $d in /proc|/sys|/dev|/run|/tmp|/newroot|/init) ;; *) cp -a \"$d\" /newroot/ || copied=0 ;; esac\n\
\t\t\tdone\n\
\t\t\tmkdir -p /newroot/proc /newroot/sys /newroot/dev /newroot/run /newroot/tmp\n\
\t\t\tif [ \"$copied\" = 1 ] && [ -x /newroot/bin/sh ]; then\n\
\t\t\t\techo rvemu-root-1 > /newroot/etc/rvemu-root || rm -f /newroot/etc/rvemu-root\n\
\t\t\tfi\n\
\t\tfi\n\
\t\tif [ -s /newroot/etc/rvemu-root ] && [ -x /newroot/bin/sh ]; then\n\
\t\t\tcp /etc/resolv.conf /newroot/etc/resolv.conf 2>/dev/null\n\
\t\t\tRSSH_REFRESH\n\
\t\t\tcat > /newroot/sbin/rvemu-session <<'RVEMU_SESSION'\n\
#!/bin/sh\n\
mount -t proc proc /proc 2>/dev/null\n\
mount -t sysfs sysfs /sys 2>/dev/null\n\
mount -t devtmpfs devtmpfs /dev 2>/dev/null\n\
mkdir -p /dev/pts /dev/shm /run /tmp\n\
mount -t devpts devpts /dev/pts\n\
mount -t tmpfs tmpfs /run\n\
mount -t tmpfs tmpfs /tmp\n\
",
    )
    .replace(
        "RSSH_REFRESH",
        &format!(
            "[ -e /newroot/usr/local/bin/.rssh-{tag} ] || {{ mkdir -p /newroot/usr/local/bin; rm -f /newroot/usr/local/bin/.rssh-*; cp /usr/local/bin/rssh /newroot/usr/local/bin/rssh && : > /newroot/usr/local/bin/.rssh-{tag}; }} 2>/dev/null",
            tag = rssh_tag()
        ),
    ) + SESSION
        + "RVEMU_SESSION\n\
\t\t\tchmod 755 /newroot/sbin/rvemu-session\n\
\t\t\tsync\n\
\t\t\texec switch_root /newroot /sbin/rvemu-session\n\
\t\tfi\n\
\t\tumount /newroot\n\
\t\techo 'rvemu: root disk is incomplete; running from memory'\n\
\telse\n\
\t\techo 'rvemu: cannot mount the root disk; running from memory'\n\
\tfi\n\
fi\n"
}

